//-------------------TEMP LUT -----------------------------------
static const uint8_t temp_raw_lut[101] = {
		33, 34, 35, 36, 37, 37, 38, 39, 40, 41, //  0% - 9%
		42, 42, 43, 44, 45, 46, 46, 47, 48, 49, // 10% - 19%
		50, 50, 51, 52, 52, 53, 53, 54, 54, 55, // 20% - 29%
		55, 56, 56, 56, 57, 57, 57, 58, 58, 58, // 30% - 39%
		59, 59, 59, 59, 59, 60, 60, 61, 61, 62, // 40% - 49%
		63, 99, 100, 100, 100, 101, 101, 101, 101, 101, // 50% - 59%
		101, 102, 102, 102, 102, 103, 103, 103, 103, 104, // 60% - 69%
		104, 104, 104, 105, 105, 105, 105, 105, 106, 106, // 70% - 79%
		106, 106, 107, 107, 107, 107, 107, 108, 108, 108, // 80% - 89%
		109, 109, 109, 110, 110, 110, 111, 111, 111, 112, // 90% - 99%
		112                                                // 100%
};
//-------------------------------------------------------------------

void Send_Engine_Temperature(uint8_t temp_lvl_pct){

	if (temp_lvl_pct > 100) {
		temp_lvl_pct = 100;
	}

	uint8_t temp_lvl_raw = temp_raw_lut[temp_lvl_pct];

	if (hi2c1.State != HAL_I2C_STATE_READY) {
	        HAL_I2C_DeInit(&hi2c1);
	        HAL_I2C_Init(&hi2c1);
	}

	MCP4661_SetWiper(&hi2c1, MCP4661_VOLATILE_WIPER_0, temp_lvl_raw);
}

void Send_Fuel_lvl(uint8_t fuel_lvl_pct){

	if (fuel_lvl_pct > 100) {
		fuel_lvl_pct = 100;
	}

	uint8_t fuel_lvl_raw = fuel_raw_lut[fuel_lvl_pct];

	if (hi2c1.State != HAL_I2C_STATE_READY) {
	        HAL_I2C_DeInit(&hi2c1);
	        HAL_I2C_Init(&hi2c1);
	}

	MCP4661_SetWiper(&hi2c1, MCP4661_VOLATILE_WIPER_1, fuel_lvl_raw);
}
